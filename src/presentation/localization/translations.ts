const translationTables: Record<Locale, Partial<Translations>> = { es, en };

export function parseLocale(raw: unknown): Locale {
  return raw === 'es' || raw === 'en' ? raw : defaultLocale;
}

export function detectLocale(navigatorLanguage: string | null | undefined): Locale {
  if (typeof navigatorLanguage !== 'string') return defaultLocale;
  return navigatorLanguage.toLowerCase().startsWith('en') ? 'en' : defaultLocale;
}

export function translate(locale: Locale, key: MessageKey, params?: Record<string, string | number>): string {
  const table = translationTables[locale] ?? translationTables[defaultLocale];
  let text = table[key] ?? es[key] ?? key;
  if (params) {
    for (const name of Object.keys(params)) {
      const value = params[name];
      text = text.split('{' + name + '}').join(String(value ?? ''));
    }
  }
  return text;
}

export function withShortcut(label: string, shortcut: string): string {
  return label + ' (' + shortcut + ')';
}
